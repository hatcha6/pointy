"""Server-side generation of the dashboard's inline AI text.

The dashboard already computes every figure it shows; this turns those figures
into a short, owner-facing brief plus a one-line explainer for a handful of the
cards — generated by a SINGLE relay call that is:

* **not persisted** — it never creates an AiConversation/AiMessage, so the
  generated summary doesn't pollute the user's chat history; and
* **not metered** — it passes ``count_usage=False`` so the daily digest never
  eats into the shop's interactive-chat quota.

The caller (the digest view) caches the result for the rest of the day, so this
runs at most once per shop per period per day.
"""

import json
import logging

from django.utils import timezone

from apps.core.models import ShopSettings
from apps.core.relay import RelayControlClient, RelayControlError

from .relay_stream import _advice_playbook, _shop_context_sentence, iter_relay_sse

logger = logging.getLogger(__name__)

# The explainer keys the model may fill — each maps to one dashboard card on the
# client. Kept in sync with the Flutter side (`_DigestKeys`). The model only
# fills the ones it has something specific and useful to say about.
DIGEST_EXPLAINER_KEYS = (
    "sales_trend",
    "profit",
    "top_products",
    "top_categories",
    "low_stock",
    "dead_stock",
    "registers",
    "overdue_purchases",
    "customers",
    "discounts",
    "fraud",
    "payment_mix",
)

# Bounds on the generated text so a misbehaving model can't bloat the dashboard.
_MAX_BRIEF_CHARS = 320
_MAX_EXPLAINER_CHARS = 220
_MAX_EXPLAINERS = 5
# Plenty for a brief + a few short lines of JSON; keeps the call cheap.
_DIGEST_MAX_TOKENS = 700


def _num(value):
    """Coerce a figure (possibly a Decimal) to a JSON-friendly number."""
    try:
        number = float(value)
    except (TypeError, ValueError):
        return 0
    return round(number, 2)


def _names(items, key, limit=4):
    out = []
    for item in items or []:
        name = (item.get(key) or "").strip()
        if name:
            out.append(name)
        if len(out) >= limit:
            break
    return out


def compact_figures(sections, period_days):
    """A small, JSON-serializable summary of the dashboard sections — only the
    numbers worth narrating. Returns ``{}`` when nothing meaningful is present."""
    figures = {"period_days": period_days}

    sales = sections.get("sales")
    if sales:
        summary = sales.get("summary") or {}
        figures["sales"] = {
            "net_sales": _num(summary.get("net_sales")),
            "net_sales_change_percent": _num(summary.get("net_sales_change_percent")),
            "order_count": int(summary.get("order_count") or 0),
            "order_count_change_percent": _num(summary.get("order_count_change_percent")),
            "average_order_value": _num(summary.get("average_order_value")),
            "gross_profit": _num(summary.get("gross_profit")),
            "profit_margin_percent": _num(summary.get("profit_margin_percent")),
            "refund_total": _num(summary.get("refund_total")),
            "top_products": [
                {"name": p.get("product_name", ""), "qty": int(p.get("quantity") or 0),
                 "profit": _num(p.get("profit"))}
                for p in (sales.get("top_products") or [])[:4]
            ],
            "top_categories": [
                {"name": c.get("category_name", ""), "revenue": _num(c.get("revenue"))}
                for c in (sales.get("top_categories") or [])[:4]
            ],
        }
        registers = sales.get("registers") or {}
        if int(registers.get("variance_count") or 0) > 0:
            figures["registers"] = {
                "variance_count": int(registers.get("variance_count") or 0),
                "variance_total": _num(registers.get("variance_total")),
            }

    profitability = sections.get("profitability")
    if profitability:
        summary = profitability.get("summary") or {}
        figures["profitability"] = {
            "net_operating_profit": _num(summary.get("net_operating_profit")),
            "operating_expense_total": _num(summary.get("operating_expense_total")),
            "gross_profit": _num(summary.get("gross_profit")),
        }

    inventory = sections.get("inventory")
    if inventory:
        summary = inventory.get("summary") or {}
        figures["inventory"] = {
            "low_stock_count": int(summary.get("low_stock_count") or 0),
            "out_of_stock_count": int(summary.get("out_of_stock_count") or 0),
            "retail_stock_value": _num(summary.get("retail_stock_value")),
            "low_stock_items": _names(inventory.get("low_stock_items"), "product_name"),
            "dead_stock_count": len(inventory.get("dusty_items") or []),
            "dead_stock_items": _names(inventory.get("dusty_items"), "product_name"),
        }

    purchasing = sections.get("purchasing")
    if purchasing:
        summary = purchasing.get("summary") or {}
        if int(summary.get("overdue_order_count") or 0) > 0:
            figures["purchasing"] = {
                "overdue_order_count": int(summary.get("overdue_order_count") or 0),
                "due_total": _num(summary.get("due_total")),
            }

    customers = sections.get("customers")
    if customers:
        summary = customers.get("summary") or {}
        figures["customers"] = {
            "active": int(summary.get("active_customer_count") or 0),
            "new": int(summary.get("new_customer_count") or 0),
            "repeat": int(summary.get("repeat_customer_count") or 0),
        }

    discounts = sections.get("discounts")
    if discounts:
        expiring = _names(discounts.get("expiring_rules"), "rule_name")
        summary = discounts.get("summary") or {}
        if expiring or _num(summary.get("sales_discount_total")) > 0:
            figures["discounts"] = {
                "expiring_rules": expiring,
                "sales_discount_total": _num(summary.get("sales_discount_total")),
            }

    fraud = sections.get("fraud")
    if fraud:
        summary = fraud.get("summary") or {}
        if int(summary.get("active_count") or 0) > 0:
            findings = fraud.get("recent_findings") or []
            figures["fraud"] = {
                "active_count": int(summary.get("active_count") or 0),
                "critical_count": int(summary.get("critical_count") or 0),
                "top_headline": (findings[0].get("headline") if findings else "") or "",
            }

    payments = sections.get("payments")
    if payments:
        methods = payments.get("methods") or []
        if methods:
            figures["payment_mix"] = [
                {"method": m.get("method", ""), "total": _num(m.get("total"))}
                for m in methods[:5]
            ]

    # Nothing but the period? Then there's nothing to narrate.
    if set(figures.keys()) <= {"period_days"}:
        return {}
    return figures


def _digest_messages(figures, shop):
    keys = "، ".join(DIGEST_EXPLAINER_KEYS)
    example = json.dumps(
        {
            "brief": "مبيعاتك ارتفعت ٨٪ هذا الشهر بفضل المشروبات، لكن ٧ أصناف أوشكت على النفاد.",
            "explainers": {
                "sales_trend": "صافي المبيعات ١٢٠٠ د.ل بزيادة ٨٪ عن الفترة السابقة.",
                "low_stock": "٧ أصناف عند حد إعادة الطلب — أعد طلبها قبل النفاد.",
            },
        },
        ensure_ascii=False,
    )
    system = (
        "أنت GPT، مستشار أعمال لصاحب متجر تجزئة. "
        + _shop_context_sentence(shop)
        + _advice_playbook(shop)
        + "ستحصل على ملخّص رقمي لأداء المتجر خلال فترة. مهمتك صياغة ملخّص يومي "
        "لصاحب المتجر باللغة العربية. "
        "أعد ردًّا JSON صالحًا فقط، دون أي نص قبله أو بعده ودون أسوار شيفرة، بهذا "
        'الشكل: {"brief": "...", "explainers": {"<key>": "..."}}. '
        f"قيمة brief جملة أو جملتان مفيدتان (حتى {_MAX_BRIEF_CHARS} حرفًا) تلخّصان "
        "حال المتجر في الفترة بأهم رقم أو رقمين فعليين وتُبرزان ما يستحق الانتباه — "
        "لا تكتفِ بعنوان عام مثل «ملخص اليوم». "
        f"و explainers خريطة من مفاتيح ضمن هذه القائمة فقط: [{keys}]، قيمة كل مفتاح "
        f"سطر تفسيري واحد قصير (حتى {_MAX_EXPLAINER_CHARS} حرفًا) مبني على أرقام ذلك "
        "القسم. "
        f"أعطِ تفسيرًا لكل قسم ظهرت له بيانات في الأرقام المعطاة (بين مفتاحين و"
        f"{_MAX_EXPLAINERS} مفاتيح)، وابدأ بالأهم أثرًا. "
        "اربط كل ملاحظة برقم من البيانات المعطاة فقط؛ لا تخترع أرقامًا ولا معايير "
        "سوق، ولا تذكر مفتاحًا لا توجد له بيانات. كن دقيقًا وعمليًّا لا عامًّا، "
        "وقدّم حين يناسب توصية صغيرة قابلة للتنفيذ. "
        f"مثال على الشكل والأسلوب المطلوبين: {example}"
    )
    user = (
        "هذه أرقام لوحة المعلومات للفترة (period_days عدد الأيام). صُغ الملخّص "
        "والتفسيرات منها فقط، وأعدها JSON فقط:\n"
        + json.dumps(figures, ensure_ascii=False)
    )
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def _parse_digest(text):
    """Extract the ``{brief, explainers}`` object from the model's reply, tolerant
    of stray prose or code fences around the JSON. Returns a sanitized dict or
    ``None`` if no usable object is found."""
    if not text:
        return None
    start = text.find("{")
    end = text.rfind("}")
    if start == -1 or end == -1 or end <= start:
        return None
    try:
        raw = json.loads(text[start : end + 1])
    except (json.JSONDecodeError, ValueError):
        return None
    if not isinstance(raw, dict):
        return None

    brief = raw.get("brief")
    brief = brief.strip()[:_MAX_BRIEF_CHARS] if isinstance(brief, str) else ""

    explainers = {}
    raw_explainers = raw.get("explainers")
    if isinstance(raw_explainers, dict):
        for key, value in raw_explainers.items():
            if key not in DIGEST_EXPLAINER_KEYS or not isinstance(value, str):
                continue
            line = value.strip()
            if line:
                explainers[key] = line[:_MAX_EXPLAINER_CHARS]
            if len(explainers) >= _MAX_EXPLAINERS:
                break

    if not brief and not explainers:
        return None
    return {"brief": brief, "explainers": explainers}


def generate_dashboard_digest(installation, sections, period_days, *, client=None):
    """Generate the inline dashboard digest from the dashboard ``sections``.

    Returns ``{"brief": str, "explainers": {key: str}, "generated_at": iso}`` or
    ``None`` when there's nothing to say or the relay call fails (the caller then
    simply renders no inline AI text — never an error)."""
    figures = compact_figures(sections, period_days)
    if not figures:
        return None

    shop = ShopSettings.load()
    messages = _digest_messages(figures, shop)
    client = client or RelayControlClient()
    try:
        response = client.open_ai_stream(
            access_token=installation.access_token,
            messages=messages,
            count_usage=False,
            max_tokens=_DIGEST_MAX_TOKENS,
            temperature=0.4,
        )
    except RelayControlError:
        logger.warning("dashboard digest: relay call failed", exc_info=True)
        return None

    chunks = []
    try:
        for event in iter_relay_sse(response):
            if event.get("event") == "delta":
                text = (event.get("data") or {}).get("text", "")
                if text:
                    chunks.append(text)
    except Exception:
        logger.warning("dashboard digest: stream read failed", exc_info=True)
        return None
    finally:
        close = getattr(response, "close", None)
        if callable(close):
            close()

    raw = "".join(chunks)
    digest = _parse_digest(raw)
    if digest is None:
        # Surface what the model actually returned so an empty dashboard digest
        # is diagnosable (bad JSON, refusal, empty stream) instead of silent.
        logger.warning(
            "dashboard digest: unparseable model output (%d chars): %s",
            len(raw),
            raw[:500],
        )
        return None
    digest["generated_at"] = timezone.now().isoformat()
    return digest
